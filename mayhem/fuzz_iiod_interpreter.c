/* Defined in iiod.c, the daemon's main(), which this harness replaces (poll_nointr is a copy). */
bool server_demux;
struct thread_pool *main_thread_pool;
struct iio_context_params iiod_params = { .log_level = LEVEL_NOLOG };

int poll_nointr(struct pollfd *pfd, unsigned int num_pfd)
{
	int ret;

	do {
		ret = poll(pfd, num_pfd, -1);
	} while (ret == -1 && errno == EINTR);

	return ret;
}

static char dir[4096];
static int listener = -1;
static struct sockaddr_in listen_addr;
static void *xml_zstd;
static size_t xml_zstd_len;

static void quiet(void *ctx, const char *msg, ...)
{
	(void)ctx;
	(void)msg;
}

static int write_file(const char *name, const void *data, size_t len)
{
	char path[4200];
	FILE *f;

	snprintf(path, sizeof(path), "%s/%s", dir, name);
	f = fopen(path, "wb");
	if (!f)
		return -1;
	fwrite(data, 1, len, f);
	return fclose(f);
}

struct client {
	int fd;
	int peer;
	const uint8_t *data;
	size_t size;
};

static void close_reset(int fd);

/* The remote end of the connection: sends the input, then hangs up its write side once iiod has read all of
 * it (iiod treats a pending hang-up as end of input even with bytes still queued), and discards whatever
 * iiod answers until iiod closes its end. */
static void *client_main(void *arg)
{
	struct client *c = arg;
	struct pollfd pfd = { .fd = c->fd };
	size_t off = 0;
	bool fin = false;
	char sink[4096];

	for (;;) {
		bool sent_all = off == c->size;

		pfd.events = POLLIN | (sent_all ? 0 : POLLOUT);
		pfd.revents = 0;
		if (poll(&pfd, 1, fin || !sent_all ? -1 : 1) < 0 && errno != EINTR)
			break;
		if (pfd.revents & POLLOUT) {
			ssize_t n = send(c->fd, c->data + off, c->size - off, MSG_NOSIGNAL | MSG_DONTWAIT);

			if (n > 0)
				off += n;
			else if (errno != EAGAIN && errno != EINTR)
				off = c->size;
		}
		if (!fin && off == c->size) {
			int pending = 0;

			if (ioctl(c->peer, FIONREAD, &pending) || !pending) {
				shutdown(c->fd, SHUT_WR);
				fin = true;
			}
		}
		if (pfd.revents & POLLIN) {
			if (read(c->fd, sink, sizeof(sink)) <= 0)
				break;
		} else if (pfd.revents & (POLLERR | POLLHUP | POLLNVAL)) {
			break;
		}
	}
	close_reset(c->fd);
	return NULL;
}

/* RST on close, so that ~100 connections a second leave no TIME_WAIT sockets behind. */
static void close_reset(int fd)
{
	struct linger l = { .l_onoff = 1, .l_linger = 0 };

	setsockopt(fd, SOL_SOCKET, SO_LINGER, &l, sizeof(l));
	close(fd);
}

/* sv[0] is the client's end, sv[1] the end iiod serves. */
static bool connect_pair(int sv[2])
{
	sv[0] = socket(AF_INET, SOCK_STREAM | SOCK_CLOEXEC, 0);
	if (sv[0] < 0)
		return false;
	if (connect(sv[0], (struct sockaddr *)&listen_addr, sizeof(listen_addr))) {
		close(sv[0]);
		return false;
	}
	sv[1] = accept4(listener, NULL, NULL, SOCK_CLOEXEC);
	if (sv[1] < 0) {
		close(sv[0]);
		return false;
	}
	return true;
}

static int init_device_pdata(struct iio_context *ctx)
{
	for (unsigned int i = 0; i < iio_context_get_devices_count(ctx); i++) {
		struct iio_device_pdata *pdata = calloc(1, sizeof(*pdata));

		if (!pdata)
			return -ENOMEM;
		pdata->nb_blocks = 4;
		iio_device_set_data(iio_context_get_device(ctx, i), pdata);
	}
	return 0;
}

static void free_device_pdata(struct iio_context *ctx)
{
	for (unsigned int i = 0; i < iio_context_get_devices_count(ctx); i++)
		free(iio_device_get_data(iio_context_get_device(ctx, i)));
}

int LLVMFuzzerInitialize(int *argc, char ***argv)
{
	const char *tmp = getenv("TMPDIR");
	struct iio_context_params params = { .log_level = LEVEL_NOLOG };
	struct iio_context *ctx;
	char uri[4200];

	(void)argc;
	(void)argv;
	xmlSetGenericErrorFunc(NULL, quiet);
	snprintf(dir, sizeof(dir), "%s/iiod-XXXXXX", tmp && *tmp ? tmp : "/tmp");
	if (!mkdtemp(dir))
		return 1;
	/* The fixtures are written once and only read afterwards. */
	if (write_file(FIXTURE_XML, fixture_xml, fixture_xml_len) ||
			write_file(FIXTURE_BIN, fixture_bin, fixture_bin_len))
		return 1;

	/* iiod's network front end serves each client over an accepted TCP connection; so does this harness. */
	listener = socket(AF_INET, SOCK_STREAM | SOCK_CLOEXEC, 0);
	listen_addr.sin_family = AF_INET;
	listen_addr.sin_addr.s_addr = htonl(INADDR_LOOPBACK);
	if (listener < 0 || bind(listener, (struct sockaddr *)&listen_addr, sizeof(listen_addr)) ||
			listen(listener, 1) ||
			getsockname(listener, (struct sockaddr *)&listen_addr, &(socklen_t){ sizeof(listen_addr) }))
		return 1;

	main_thread_pool = thread_pool_new();
	buflist_lock = iio_mutex_create();
	evlist_lock = iio_mutex_create();
	if (!main_thread_pool || iio_err(buflist_lock) || iio_err(evlist_lock))
		return 1;

	/* The compressed XML iiod hands to ZPRINT is computed once, as iiod does at startup, and only read. */
	snprintf(uri, sizeof(uri), "emu:%s/" FIXTURE_XML, dir);
	ctx = iio_create_context(&params, uri);
	if (iio_err(ctx))
		return 1;
	xml_zstd = iiod_get_xml_zstd(ctx, &xml_zstd_len);
	iio_context_destroy(ctx);
	return 0;
}

int LLVMFuzzerTestOneInput(const uint8_t *data, size_t size)
{
	struct iio_context_params params = { .log_level = LEVEL_NOLOG };
	struct iio_context *ctx;
	char uri[4200], path[4200];
	pthread_t thread;
	DIR *d;
	int sv[2];

	snprintf(uri, sizeof(uri), "emu:%s/" FIXTURE_XML, dir);
	ctx = iio_create_context(&params, uri);
	if (iio_err(ctx))
		return 0;
	if (init_device_pdata(ctx)) {
		free_device_pdata(ctx);
		iio_context_destroy(ctx);
		return 0;
	}

	if (connect_pair(sv)) {
		struct client c = { .fd = sv[0], .peer = sv[1], .data = data, .size = size };

		if (!pthread_create(&thread, NULL, client_main, &c)) {
			interpreter(ctx, sv[1], sv[1], true, false, main_thread_pool, xml_zstd, xml_zstd_len);
			shutdown(sv[1], SHUT_RDWR);
			pthread_join(thread, NULL);
			close_reset(sv[1]);
		} else {
			close_reset(sv[0]);
			close_reset(sv[1]);
		}
	}

	/* Like iiod's shutdown: let every read/write thread release its buffers before the context goes. */
	thread_pool_stop_and_wait(main_thread_pool);
	thread_pool_restart(main_thread_pool);
	free_device_pdata(ctx);
	iio_context_destroy(ctx);

	/* Each input gets a fresh emulated context; the files it wrote (TX buffers) are removed. */
	d = opendir(dir);
	if (d) {
		struct dirent *e;

		while ((e = readdir(d))) {
			if (e->d_name[0] == '.' || !strcmp(e->d_name, FIXTURE_XML) ||
					!strcmp(e->d_name, FIXTURE_BIN))
				continue;
			snprintf(path, sizeof(path), "%s/%s", dir, e->d_name);
			unlink(path);
		}
		closedir(d);
	}
	return 0;
}
